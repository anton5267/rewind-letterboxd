-- Persist authenticated user reports for review moderation.
-- Report reasons match the visible values in the READY Reported Reviews design.

CREATE TABLE rewind.review_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id BIGINT NOT NULL REFERENCES rewind.reviews(id) ON DELETE CASCADE,
  reporter_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  reason VARCHAR(40) NOT NULL CHECK (reason IN ('SPAM', 'INAPPROPRIATE_CONTENT', 'BULLYING')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT review_reports_uq_review_reporter UNIQUE (review_id, reporter_id)
);

CREATE INDEX review_reports_created_id_idx ON rewind.review_reports(created_at DESC, id DESC);

ALTER TABLE rewind.review_reports ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT (review_id, reporter_id, reason) ON rewind.review_reports TO rewind_edge_app;
GRANT USAGE, SELECT ON SEQUENCE rewind.review_reports_id_seq TO rewind_edge_app;

CREATE POLICY edge_app_review_report_insert ON rewind.review_reports
  FOR INSERT TO rewind_edge_app
  WITH CHECK (
    reporter_id = rewind.current_rewind_user_id()
    AND EXISTS (
      SELECT 1 FROM rewind.reviews r
      JOIN rewind.users author ON author.id = r.user_id
      WHERE r.id = review_reports.review_id
        AND r.user_id <> rewind.current_rewind_user_id()
        AND r.is_hidden = FALSE
        AND author.is_active = TRUE
    )
  );

CREATE POLICY edge_app_review_report_read ON rewind.review_reports
  FOR SELECT TO rewind_edge_app
  USING (
    reporter_id = rewind.current_rewind_user_id()
    OR rewind.current_user_is_admin()
  );
