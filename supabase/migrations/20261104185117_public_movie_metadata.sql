-- Extend the read-only movie catalogue with public detail metadata.
-- Do not add user accounts, reviews, lists, or other user-generated data here.

ALTER TABLE rewind.movies
  ADD COLUMN imdb_id VARCHAR(20),
  ADD COLUMN tmdb_id BIGINT,
  ADD COLUMN duration_minutes INTEGER,
  ADD COLUMN age_rating VARCHAR(10),
  ADD COLUMN short_plot TEXT,
  ADD COLUMN backdrop_url VARCHAR(255),
  ADD COLUMN trailer_url VARCHAR(255);

CREATE UNIQUE INDEX movies_imdb_id_key ON rewind.movies (imdb_id);
CREATE UNIQUE INDEX movies_tmdb_id_key ON rewind.movies (tmdb_id);

CREATE TABLE rewind.actors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  tmdb_id BIGINT UNIQUE,
  photo_url VARCHAR(255)
);

CREATE TABLE rewind.directors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  tmdb_id BIGINT UNIQUE,
  photo_url VARCHAR(255)
);

CREATE TABLE rewind.movie_actors (
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  actor_id BIGINT NOT NULL REFERENCES rewind.actors(id) ON DELETE CASCADE,
  character_name VARCHAR(150),
  cast_order INTEGER,
  PRIMARY KEY (movie_id, actor_id)
);
CREATE INDEX movie_actors_actor_order_idx ON rewind.movie_actors (actor_id, cast_order);

CREATE TABLE rewind.movie_directors (
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  director_id BIGINT NOT NULL REFERENCES rewind.directors(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, director_id)
);

CREATE TABLE rewind.external_ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  source VARCHAR(10) NOT NULL CHECK (source IN ('IMDB', 'TMDB')),
  rating NUMERIC(3,1) NOT NULL,
  votes_count INTEGER,
  last_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (movie_id, source)
);

CREATE TABLE rewind.similar_movies (
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  similar_movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, similar_movie_id),
  CHECK (movie_id <> similar_movie_id)
);
CREATE INDEX similar_movies_similar_movie_idx ON rewind.similar_movies (similar_movie_id, movie_id);

REVOKE ALL ON TABLE rewind.movies, rewind.actors, rewind.directors,
  rewind.movie_actors, rewind.movie_directors, rewind.external_ratings,
  rewind.similar_movies FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON TABLE rewind.movies, rewind.actors, rewind.directors, rewind.movie_actors, rewind.movie_directors, rewind.external_ratings, rewind.similar_movies FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON TABLE rewind.movies, rewind.actors, rewind.directors, rewind.movie_actors, rewind.movie_directors, rewind.external_ratings, rewind.similar_movies FROM authenticated';
  END IF;
END
$$;
GRANT SELECT ON TABLE rewind.movies, rewind.actors, rewind.directors,
  rewind.movie_actors, rewind.movie_directors, rewind.external_ratings,
  rewind.similar_movies TO rewind_edge_reader;
