ALTER TABLE rewind.ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE rewind.lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE rewind.list_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE rewind.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE rewind.comments ENABLE ROW LEVEL SECURITY;

