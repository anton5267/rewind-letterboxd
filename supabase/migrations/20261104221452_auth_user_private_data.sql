-- Add the first hosted account and user-generated data tables without importing
-- any local MySQL users or personal data. The REWIND account remains numeric;
-- Supabase Auth UUID is a separate, nullable identity link.

ALTER TABLE rewind.genres ADD COLUMN IF NOT EXISTS tmdb_id BIGINT;
ALTER TABLE rewind.movies
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE ROLE rewind_edge_app NOLOGIN;
GRANT rewind_edge_app TO postgres;
GRANT USAGE ON SCHEMA rewind TO rewind_edge_app;
GRANT SELECT ON rewind.genres, rewind.movies, rewind.movie_genres,
  rewind.actors, rewind.movie_actors, rewind.directors, rewind.movie_directors,
  rewind.external_ratings, rewind.similar_movies TO rewind_edge_app;

CREATE TABLE rewind.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(255) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER','ADMIN')),
  avatar_url VARCHAR(255),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  display_name VARCHAR(60),
  is_hq BOOLEAN NOT NULL DEFAULT FALSE,
  supabase_user_id VARCHAR(36) UNIQUE
);

CREATE TABLE rewind.ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, movie_id)
);
CREATE INDEX ratings_user_updated_idx ON rewind.ratings(user_id, updated_at);
CREATE INDEX ratings_movie_idx ON rewind.ratings(movie_id);

CREATE TABLE rewind.lists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  description TEXT,
  list_type VARCHAR(255) NOT NULL DEFAULT 'CUSTOM'
    CHECK (list_type IN ('CUSTOM','WATCHED','WATCHLIST','FAVORITES')),
  is_public BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX lists_user_type_idx ON rewind.lists(user_id, list_type);
CREATE INDEX lists_public_updated_idx ON rewind.lists(is_public, updated_at);

CREATE TABLE rewind.list_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_id BIGINT NOT NULL REFERENCES rewind.lists(id) ON DELETE CASCADE,
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  position INTEGER,
  added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (list_id, movie_id)
);
CREATE INDEX list_items_list_position_idx ON rewind.list_items(list_id, position, id);

CREATE TABLE rewind.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  rating SMALLINT CHECK (rating BETWEEN 1 AND 5),
  is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
  moderated_reason VARCHAR(255),
  moderated_at TIMESTAMPTZ,
  moderated_by BIGINT REFERENCES rewind.users(id) ON DELETE SET NULL,
  UNIQUE (user_id, movie_id)
);
CREATE INDEX reviews_movie_visible_created_idx ON rewind.reviews(movie_id, is_hidden, created_at);
CREATE INDEX reviews_user_updated_idx ON rewind.reviews(user_id, updated_at);

CREATE TABLE rewind.comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id BIGINT NOT NULL REFERENCES rewind.reviews(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
  moderated_reason VARCHAR(255),
  moderated_at TIMESTAMPTZ,
  moderated_by BIGINT REFERENCES rewind.users(id) ON DELETE SET NULL
);
CREATE INDEX comments_review_created_idx ON rewind.comments(review_id, created_at);
CREATE INDEX comments_user_idx ON rewind.comments(user_id);

CREATE OR REPLACE FUNCTION rewind.current_supabase_uid() RETURNS TEXT
LANGUAGE SQL STABLE
SET search_path = pg_catalog
AS $$ SELECT NULLIF(current_setting('rewind.supabase_user_id', TRUE), '') $$;

CREATE OR REPLACE FUNCTION rewind.current_rewind_user_id() RETURNS BIGINT
LANGUAGE SQL STABLE
SET search_path = pg_catalog
AS $$ SELECT NULLIF(current_setting('rewind.user_id', TRUE), '')::BIGINT $$;

REVOKE ALL ON FUNCTION rewind.current_supabase_uid() FROM PUBLIC;
REVOKE ALL ON FUNCTION rewind.current_rewind_user_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION rewind.current_supabase_uid(), rewind.current_rewind_user_id()
  TO rewind_edge_app;

GRANT SELECT (id, username, avatar_url, display_name, role, is_active, supabase_user_id),
  INSERT (username, email, password_hash, avatar_url, display_name, supabase_user_id)
  ON rewind.users TO rewind_edge_app;
GRANT UPDATE (username, avatar_url, display_name) ON rewind.users TO rewind_edge_app;
GRANT USAGE, SELECT ON SEQUENCE rewind.users_id_seq TO rewind_edge_app;

GRANT SELECT, DELETE ON rewind.ratings, rewind.lists, rewind.list_items,
  rewind.reviews, rewind.comments TO rewind_edge_app;
GRANT INSERT (user_id, movie_id, rating) ON rewind.ratings TO rewind_edge_app;
GRANT UPDATE (rating, updated_at) ON rewind.ratings TO rewind_edge_app;
GRANT INSERT (user_id, name, description, list_type, is_public) ON rewind.lists TO rewind_edge_app;
GRANT UPDATE (name, description, list_type, is_public, updated_at) ON rewind.lists TO rewind_edge_app;
GRANT INSERT (list_id, movie_id, position) ON rewind.list_items TO rewind_edge_app;
GRANT UPDATE (list_id, position) ON rewind.list_items TO rewind_edge_app;
GRANT INSERT (user_id, movie_id, content, rating) ON rewind.reviews TO rewind_edge_app;
GRANT UPDATE (content, rating, updated_at) ON rewind.reviews TO rewind_edge_app;
GRANT INSERT (review_id, user_id, content) ON rewind.comments TO rewind_edge_app;
GRANT UPDATE (content, updated_at) ON rewind.comments TO rewind_edge_app;
GRANT USAGE, SELECT ON SEQUENCE rewind.ratings_id_seq, rewind.lists_id_seq,
  rewind.list_items_id_seq, rewind.reviews_id_seq, rewind.comments_id_seq TO rewind_edge_app;

