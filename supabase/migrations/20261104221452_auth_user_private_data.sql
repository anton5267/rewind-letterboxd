CREATE OR REPLACE FUNCTION rewind.touch_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION rewind.touch_updated_at() FROM PUBLIC;
CREATE TRIGGER users_touch_updated_at BEFORE UPDATE ON rewind.users
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();
CREATE TRIGGER ratings_touch_updated_at BEFORE UPDATE ON rewind.ratings
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();
CREATE TRIGGER lists_touch_updated_at BEFORE UPDATE ON rewind.lists
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();
CREATE TRIGGER reviews_touch_updated_at BEFORE UPDATE ON rewind.reviews
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();
CREATE TRIGGER comments_touch_updated_at BEFORE UPDATE ON rewind.comments
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();
CREATE TRIGGER movies_touch_updated_at BEFORE UPDATE ON rewind.movies
  FOR EACH ROW EXECUTE FUNCTION rewind.touch_updated_at();

