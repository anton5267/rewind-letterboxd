-- Add private report queues for visible comments and public custom lists.
-- Only the Edge role receives table access; RLS remains the row-level boundary.

CREATE TABLE rewind.comment_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id BIGINT NOT NULL REFERENCES rewind.comments(id) ON DELETE CASCADE,
  reporter_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  reason VARCHAR(40) NOT NULL CHECK (reason IN ('SPAM', 'INAPPROPRIATE_CONTENT', 'BULLYING')),
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DISMISSED', 'ACTION_TAKEN')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  reviewed_by BIGINT REFERENCES rewind.users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX comment_reports_uq_open_reporter
  ON rewind.comment_reports(comment_id, reporter_id) WHERE status = 'OPEN';
CREATE INDEX comment_reports_created_id_idx ON rewind.comment_reports(created_at DESC, id DESC);
CREATE INDEX comment_reports_reporter_id_idx ON rewind.comment_reports(reporter_id);
CREATE INDEX comment_reports_reviewed_by_idx ON rewind.comment_reports(reviewed_by);

ALTER TABLE rewind.comment_reports ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT (comment_id, reporter_id, reason) ON rewind.comment_reports TO rewind_edge_app;
GRANT UPDATE (status, reviewed_at, reviewed_by) ON rewind.comment_reports TO rewind_edge_app;
GRANT USAGE, SELECT ON SEQUENCE rewind.comment_reports_id_seq TO rewind_edge_app;

CREATE POLICY edge_app_comment_report_insert ON rewind.comment_reports
  FOR INSERT TO rewind_edge_app
  WITH CHECK (
    reporter_id = rewind.current_rewind_user_id()
    AND EXISTS (
      SELECT 1 FROM rewind.comments c
      JOIN rewind.reviews r ON r.id = c.review_id
      JOIN rewind.users comment_author ON comment_author.id = c.user_id
      JOIN rewind.users review_author ON review_author.id = r.user_id
      WHERE c.id = comment_reports.comment_id
        AND c.user_id <> rewind.current_rewind_user_id()
        AND c.is_hidden = FALSE AND r.is_hidden = FALSE
        AND comment_author.is_active = TRUE AND review_author.is_active = TRUE
    )
  );
CREATE POLICY edge_app_comment_report_read ON rewind.comment_reports
  FOR SELECT TO rewind_edge_app
  USING (reporter_id = rewind.current_rewind_user_id() OR rewind.current_user_is_admin());
CREATE POLICY edge_app_comment_report_update ON rewind.comment_reports
  FOR UPDATE TO rewind_edge_app
  USING (rewind.current_user_is_admin())
  WITH CHECK (rewind.current_user_is_admin());

CREATE TABLE rewind.list_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_id BIGINT NOT NULL REFERENCES rewind.lists(id) ON DELETE CASCADE,
  reporter_id BIGINT NOT NULL REFERENCES rewind.users(id) ON DELETE CASCADE,
  reason VARCHAR(40) NOT NULL CHECK (reason IN ('SPAM', 'INAPPROPRIATE_CONTENT', 'BULLYING')),
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DISMISSED', 'ACTION_TAKEN')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  reviewed_by BIGINT REFERENCES rewind.users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX list_reports_uq_open_reporter
  ON rewind.list_reports(list_id, reporter_id) WHERE status = 'OPEN';
CREATE INDEX list_reports_created_id_idx ON rewind.list_reports(created_at DESC, id DESC);
CREATE INDEX list_reports_reporter_id_idx ON rewind.list_reports(reporter_id);
CREATE INDEX list_reports_reviewed_by_idx ON rewind.list_reports(reviewed_by);

ALTER TABLE rewind.list_reports ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT (list_id, reporter_id, reason) ON rewind.list_reports TO rewind_edge_app;
GRANT UPDATE (status, reviewed_at, reviewed_by) ON rewind.list_reports TO rewind_edge_app;
GRANT USAGE, SELECT ON SEQUENCE rewind.list_reports_id_seq TO rewind_edge_app;

CREATE POLICY edge_app_list_report_insert ON rewind.list_reports
  FOR INSERT TO rewind_edge_app
  WITH CHECK (
    reporter_id = rewind.current_rewind_user_id()
    AND EXISTS (
      SELECT 1 FROM rewind.lists l
      JOIN rewind.users list_owner ON list_owner.id = l.user_id
      WHERE l.id = list_reports.list_id
        AND l.list_type = 'CUSTOM' AND l.is_public = TRUE
        AND l.user_id <> rewind.current_rewind_user_id()
        AND list_owner.is_active = TRUE
    )
  );
CREATE POLICY edge_app_list_report_read ON rewind.list_reports
  FOR SELECT TO rewind_edge_app
  USING (reporter_id = rewind.current_rewind_user_id() OR rewind.current_user_is_admin());
CREATE POLICY edge_app_list_report_update ON rewind.list_reports
  FOR UPDATE TO rewind_edge_app
  USING (rewind.current_user_is_admin())
  WITH CHECK (rewind.current_user_is_admin());
