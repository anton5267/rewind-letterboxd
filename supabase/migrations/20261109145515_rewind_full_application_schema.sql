CREATE TABLE admin_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  admin_id BIGINT NOT NULL,
  action varchar(80) NOT NULL,
  target_type varchar(40) NOT NULL,
  target_id BIGINT DEFAULT NULL,
  metadata text,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)

);

CREATE TABLE conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_one_id BIGINT NOT NULL,
  user_two_id BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT conversations_uq_conversation_pair UNIQUE (user_one_id,user_two_id),
  CONSTRAINT chk_conversation_distinct_users CHECK ((user_one_id < user_two_id))

);

CREATE TABLE follows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  follower_id BIGINT NOT NULL,
  following_id BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT follows_uk_follows_pair UNIQUE (follower_id,following_id),
  CONSTRAINT chk_follows_not_self CHECK ((follower_id <> following_id))

);

CREATE TABLE journal_articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug varchar(180) NOT NULL,
  language varchar(2) NOT NULL,
  category varchar(80) NOT NULL,
  title varchar(255) NOT NULL,
  excerpt varchar(500) DEFAULT NULL,
  content text NOT NULL,
  cover_url varchar(500) DEFAULT NULL,
  audio_url varchar(500) DEFAULT NULL,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  published_at TIMESTAMP WITH TIME ZONE NULL DEFAULT NULL,
  author_id BIGINT DEFAULT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT journal_articles_uq_journal_articles_slug_language UNIQUE (slug,language)

);

CREATE TABLE list_likes (
