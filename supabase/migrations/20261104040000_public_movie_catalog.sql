-- Read-only public catalogue for the temporary GitHub Pages launch.
-- Application tables live in the unexposed `rewind` schema; Auth schema is untouched.
CREATE SCHEMA rewind;
REVOKE ALL ON SCHEMA rewind FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA rewind FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA rewind FROM authenticated';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rewind_edge_reader') THEN
    CREATE ROLE rewind_edge_reader NOLOGIN;
  END IF;
END
$$;

CREATE TABLE rewind.genres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE rewind.movies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  release_date DATE,
  rating NUMERIC(3,1),
  photo_url VARCHAR(255)
);

CREATE TABLE rewind.movie_genres (
  movie_id BIGINT NOT NULL REFERENCES rewind.movies(id) ON DELETE CASCADE,
  genre_id BIGINT NOT NULL REFERENCES rewind.genres(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, genre_id)
);

CREATE INDEX movie_genres_genre_movie_idx ON rewind.movie_genres (genre_id, movie_id);
GRANT USAGE ON SCHEMA rewind TO rewind_edge_reader;
GRANT SELECT ON rewind.genres, rewind.movies, rewind.movie_genres TO rewind_edge_reader;
GRANT rewind_edge_reader TO postgres;
